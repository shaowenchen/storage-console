/** Menu visibility helper — server still re-checks MIME + size. */
export function looksLikeTextFileName(keyOrName: string): boolean {
  const base = keyOrName.split('/').filter(Boolean).pop() || keyOrName;
  if (!base.includes('.')) {
    const lower = base.toLowerCase();
    return lower === 'dockerfile' || lower === 'makefile' || lower === 'jenkinsfile';
  }
  const ext = base.split('.').pop()?.toLowerCase() || '';
  return TEXT_EXTENSIONS.has(ext);
}
